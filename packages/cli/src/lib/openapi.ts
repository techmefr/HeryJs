import { existsSync, readdirSync } from 'node:fs';
import * as path from 'node:path';
import { loadBlueprint } from './blueprint';
import { buildResourceContext } from './resource-context';
import type { ResourceContext } from './resource-context';
import {
  OPENAPI_ABSENCES,
  ownRouteIncludes,
  typeNameOf,
} from './openapi-contract';
import { pathsFor } from './openapi-paths';
import {
  childQuery,
  childRowSchema,
  describeSchema,
  historySchemas,
  mutationSchemas,
  queryRequestSchemas,
  recordSchema,
  resourceQuery,
  searchHitSchema,
  sharedSchemas,
} from './openapi-schemas';
import type { JsonSchema, SchemaRegistry } from './openapi-schemas';

export interface OpenApiDocumentOptions {
  title?: string;
  version?: string;
}

export function discoverResourceContexts(dir: string): ResourceContext[] {
  if (!existsSync(dir)) {
    return [];
  }

  return readdirSync(dir)
    .filter((file) => file.endsWith('.yaml') || file.endsWith('.yml'))
    .sort()
    .map((file) => loadBlueprint(path.join(dir, file)))
    .filter((blueprint) => blueprint.routed)
    .map((blueprint) => buildResourceContext(blueprint));
}

function schemasFor(ctx: ResourceContext): SchemaRegistry {
  const name = typeNameOf(ctx);
  const registry: SchemaRegistry = {
    [name]: recordSchema(ctx),
    [`${name}SearchHit`]: searchHitSchema(ctx),
    [`${name}Describe`]: describeSchema(ctx),
    ...queryRequestSchemas(resourceQuery(ctx)),
    ...mutationSchemas(ctx),
  };

  if (ctx.history) {
    Object.assign(registry, historySchemas(ctx));
  }

  for (const include of ownRouteIncludes(ctx)) {
    const query = childQuery(ctx, include);
    Object.assign(registry, queryRequestSchemas(query), {
      [`${query.name}Row`]: childRowSchema(include),
    });
  }

  return registry;
}

export function buildOpenApiDocument(
  contexts: ResourceContext[],
  options: OpenApiDocumentOptions = {},
): JsonSchema {
  const paths: Record<string, JsonSchema> = {};
  const schemas: SchemaRegistry = sharedSchemas();

  for (const ctx of contexts) {
    Object.assign(paths, pathsFor(ctx));
    Object.assign(schemas, schemasFor(ctx));
  }

  return {
    openapi: '3.1.0',
    info: {
      title: options.title ?? 'HeryJs API',
      version: options.version ?? '1.0.0',
      description: [
        "Generated by `hery openapi` from the same blueprint data each resource's GET /<resource>/describe publishes.",
        'What the spec does not claim, because /describe does not know it:',
        ...OPENAPI_ABSENCES.map((absence) => `- ${absence}`),
      ].join('\n'),
    },
    paths,
    components: {
      securitySchemes: { bearerAuth: { type: 'http', scheme: 'bearer' } },
      schemas,
    },
  };
}
