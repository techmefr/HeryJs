import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';
import { format, resolveConfig } from 'prettier';
import {
  KERNEL_COPY_DIRS,
  copiedKernelFiles,
  isAppSideKernelFile,
} from '../packages/cli/src/lib/kernel-dependency';

const REPO_ROOT = path.resolve(__dirname, '..');
const MANIFEST = path.join(
  'packages',
  'cli',
  'src',
  'lib',
  'kernel-versions.ts',
);
const HISTORY_REF = 'origin/main';

function git(args: string[], input?: string): Buffer {
  return execFileSync('git', args, {
    cwd: REPO_ROOT,
    input,
    maxBuffer: 1024 * 1024 * 1024,
  });
}

function sha256(content: Buffer): string {
  return createHash('sha256').update(content).digest('hex');
}

function posix(file: string): string {
  return file.split(path.sep).join('/');
}

/**
 * Every blob each kernel path has had on main, read straight from the object
 * store: `git cat-file --batch` answers each id with a header line and the
 * raw content, which is what a project's copy is compared against.
 */
function historicalVersions(): Map<string, Set<string>> {
  const dirs = KERNEL_COPY_DIRS.map(posix);
  const commits = git(['rev-list', HISTORY_REF, '--', ...dirs])
    .toString()
    .split('\n')
    .filter(Boolean);
  const blobsByPath = new Map<string, Set<string>>();

  for (const commit of commits) {
    const listing = git(['ls-tree', '-r', commit, '--', ...dirs]).toString();

    for (const line of listing.split('\n').filter(Boolean)) {
      const [meta, file] = line.split('\t') as [string, string];
      const [, type, id] = meta.split(' ') as [string, string, string];

      if (type !== 'blob' || isAppSideKernelFile(path.normalize(file))) {
        continue;
      }

      const ids = blobsByPath.get(file) ?? new Set<string>();
      ids.add(id);
      blobsByPath.set(file, ids);
    }
  }

  const ids = [
    ...new Set([...blobsByPath.values()].flatMap((set) => [...set])),
  ];
  const output = git(['cat-file', '--batch'], `${ids.join('\n')}\n`);
  const hashOf = new Map<string, string>();
  let offset = 0;

  while (offset < output.length) {
    const headerEnd = output.indexOf(0x0a, offset);
    const [id, , size] = output
      .subarray(offset, headerEnd)
      .toString()
      .split(' ');
    const start = headerEnd + 1;
    const end = start + Number(size);

    hashOf.set(id!, sha256(output.subarray(start, end)));
    offset = end + 1;
  }

  const versions = new Map<string, Set<string>>();

  for (const [file, blobIds] of blobsByPath) {
    versions.set(file, new Set([...blobIds].map((id) => hashOf.get(id)!)));
  }

  return versions;
}

export async function kernelVersionsSource(): Promise<string> {
  const versions = historicalVersions();

  for (const file of copiedKernelFiles(REPO_ROOT)) {
    const key = posix(file);
    const hashes = versions.get(key) ?? new Set<string>();
    hashes.add(sha256(readFileSync(path.join(REPO_ROOT, file))));
    versions.set(key, hashes);
  }

  const entries = [...versions.keys()].sort().map(
    (file) =>
      `  ${JSON.stringify(file)}: [${[...versions.get(file)!]
        .sort()
        .map((hash) => JSON.stringify(hash))
        .join(', ')}],`,
  );
  const source = `/**
 * Generated by \`pnpm run kernel:versions\` -- do not edit. The sha256 of every
 * version each file of src/technical and src/devtools has had on main, the
 * working tree included. A project generated when \`hery new\` still copied the
 * kernel carries one of them, byte for byte, unless it changed the file, and
 * \`hery kernel:migrate\` accepts exactly those.
 */
export const KERNEL_FILE_VERSIONS: Readonly<
  Record<string, readonly string[]>
> = {
${entries.join('\n')}
};
`;

  return format(source, {
    ...(await resolveConfig(path.join(REPO_ROOT, MANIFEST))),
    filepath: path.join(REPO_ROOT, MANIFEST),
  });
}

export async function checkKernelVersions(): Promise<boolean> {
  const expected = await kernelVersionsSource();
  const actual = readFileSync(path.join(REPO_ROOT, MANIFEST), 'utf8');

  if (expected !== actual) {
    console.error(
      `${MANIFEST} does not list every version of the kernel files on ${HISTORY_REF} and in the working tree. Run "pnpm run kernel:versions" and commit the result: without it, a project carrying the kernel as it was would be refused by "hery kernel:migrate".`,
    );
    return false;
  }

  console.log(
    `✔ ${MANIFEST} lists every version of the kernel files on ${HISTORY_REF}`,
  );

  return true;
}

if (require.main === module && process.argv.includes('--write')) {
  void kernelVersionsSource().then((source) =>
    writeFileSync(path.join(REPO_ROOT, MANIFEST), source),
  );
}
